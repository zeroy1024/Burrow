"""Collect the pinned license texts shipped in Burrow's native packages."""

import argparse
from pathlib import Path


project_root = Path(__file__).resolve().parent.parent
output = project_root / "THIRD_PARTY_NOTICES.md"
sources = [
    *sorted((project_root / "internal/desktop/licenses").glob("*.txt")),
    project_root / "internal/termtheme/LICENSES.md",
    project_root / "internal/uikit/icons/lucide/LICENSE",
    project_root / "third_party/mygo-terminal/LICENSE",
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the committed notice without rewriting it")
    args = parser.parse_args()
    sections = [
        "# Third-party notices\n\n"
        "Burrow's own code is licensed under the [MIT License](LICENSE). "
        "Third-party code and assets retain their respective licenses below.\n\n"
        "Generated by `python3 scripts/licenses.py` from the pinned license texts. "
        "The complete notice and Burrow's LICENSE ship as native application resources; "
        "the About page also exposes the dependency licenses.\n"
    ]
    for source in sources:
        relative = source.relative_to(project_root).as_posix()
        sections.append(f"\n## {relative}\n\n~~~~text\n{source.read_text(encoding='utf-8').rstrip()}\n~~~~\n")
    notice = "".join(sections)
    if args.check:
        if output.read_text(encoding="utf-8") != notice:
            raise SystemExit("THIRD_PARTY_NOTICES.md is stale; run python3 scripts/licenses.py")
    else:
        output.write_text(notice, encoding="utf-8")


if __name__ == "__main__":
    main()
